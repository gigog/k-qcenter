CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(40) NOT NULL UNIQUE,
  display_name VARCHAR(160) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(40) NOT NULL DEFAULT 'admin',
  scope_type VARCHAR(20) NOT NULL DEFAULT 'ALL',
  scope_id BIGINT UNSIGNED NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS buildings (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(255) NOT NULL,
  is_24_hours TINYINT(1) NOT NULL DEFAULT 0,
  open_time TIME NULL, close_time TIME NULL, active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS branches (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  building_id BIGINT UNSIGNED NULL,
  code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL,
  open_time TIME NOT NULL DEFAULT '08:30:00', close_time TIME NOT NULL DEFAULT '20:00:00',
  closing_buffer_minutes INT UNSIGNED NOT NULL DEFAULT 30, active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_branches_building FOREIGN KEY(building_id) REFERENCES buildings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS departments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, branch_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(40) NOT NULL, name VARCHAR(255) NOT NULL, counter_count INT UNSIGNED NOT NULL DEFAULT 1,
  efficiency DECIMAL(5,4) NOT NULL DEFAULT 0.8000, online_quota_percent INT UNSIGNED NOT NULL DEFAULT 70,
  walkin_quota_percent INT UNSIGNED NOT NULL DEFAULT 20, reserve_quota_percent INT UNSIGNED NOT NULL DEFAULT 10,
  daily_capacity INT UNSIGNED NULL, unlimited_capacity TINYINT(1) NOT NULL DEFAULT 0, slot_minutes INT UNSIGNED NULL,
  active TINYINT(1) NOT NULL DEFAULT 1, UNIQUE KEY uq_department_code(branch_id,code),
  CONSTRAINT fk_departments_branch FOREIGN KEY(branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS services (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, department_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL, average_minutes INT UNSIGNED NOT NULL,
  preparation_minutes INT UNSIGNED NOT NULL DEFAULT 0, slot_minutes INT UNSIGNED NOT NULL DEFAULT 30,
  default_capacity INT UNSIGNED NOT NULL DEFAULT 1, active TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT fk_services_department FOREIGN KEY(department_id) REFERENCES departments(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS kiosk_templates (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, building_id BIGINT UNSIGNED NOT NULL,
  code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(255) NOT NULL, location_label VARCHAR(255) NULL,
  active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_kiosk_template_building FOREIGN KEY(building_id) REFERENCES buildings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS kiosk_menu_items (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, template_id BIGINT UNSIGNED NOT NULL,
  parent_id BIGINT UNSIGNED NULL, department_id BIGINT UNSIGNED NULL, service_id BIGINT UNSIGNED NULL,
  label VARCHAR(255) NOT NULL, subtitle VARCHAR(255) NULL, icon VARCHAR(20) NOT NULL DEFAULT 'Q',
  sort_order INT UNSIGNED NOT NULL DEFAULT 0, start_time TIME NULL, end_time TIME NULL, schedule_json TEXT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_kiosk_menu_template(template_id,parent_id,sort_order),
  CONSTRAINT fk_kiosk_menu_template FOREIGN KEY(template_id) REFERENCES kiosk_templates(id) ON DELETE CASCADE,
  CONSTRAINT fk_kiosk_menu_parent FOREIGN KEY(parent_id) REFERENCES kiosk_menu_items(id) ON DELETE CASCADE,
  CONSTRAINT fk_kiosk_menu_department FOREIGN KEY(department_id) REFERENCES departments(id),
  CONSTRAINT fk_kiosk_menu_service FOREIGN KEY(service_id) REFERENCES services(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS calendar_overrides (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, branch_id BIGINT UNSIGNED NOT NULL, override_date DATE NOT NULL,
  name VARCHAR(255) NOT NULL, is_closed TINYINT(1) NOT NULL DEFAULT 0, open_time TIME NULL, close_time TIME NULL,
  note TEXT NULL, active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_calendar(branch_id,override_date),
  CONSTRAINT fk_calendar_branch FOREIGN KEY(branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS weekly_hours (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, scope_type VARCHAR(20) NOT NULL, scope_id BIGINT UNSIGNED NOT NULL,
  weekday TINYINT UNSIGNED NOT NULL, interval_order INT UNSIGNED NOT NULL DEFAULT 1,
  open_time TIME NOT NULL, close_time TIME NOT NULL, active TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uq_weekly(scope_type,scope_id,weekday,interval_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS weekly_schedule_config (
  scope_type VARCHAR(20) NOT NULL, scope_id BIGINT UNSIGNED NOT NULL,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(scope_type,scope_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS schedule_overrides (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, scope_type VARCHAR(20) NOT NULL, scope_id BIGINT UNSIGNED NOT NULL,
  override_date DATE NOT NULL, name VARCHAR(255) NOT NULL, is_closed TINYINT(1) NOT NULL DEFAULT 0,
  open_time TIME NULL, close_time TIME NULL, counter_count INT UNSIGNED NULL, note TEXT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_schedule_override(scope_type,scope_id,override_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS slots (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, department_id BIGINT UNSIGNED NOT NULL, service_id BIGINT UNSIGNED NULL,
  slot_date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL, capacity INT UNSIGNED NOT NULL,
  online_capacity INT UNSIGNED NOT NULL DEFAULT 0, walkin_capacity INT UNSIGNED NOT NULL DEFAULT 0,
  reserve_capacity INT UNSIGNED NOT NULL DEFAULT 0, provider_count INT UNSIGNED NOT NULL DEFAULT 1,
  capacity_locked TINYINT(1) NOT NULL DEFAULT 0, capacity_mode VARCHAR(20) NOT NULL DEFAULT 'AUTO', unlimited_capacity TINYINT(1) NOT NULL DEFAULT 0,
  booked_count INT UNSIGNED NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_slot(department_id,service_id,slot_date,start_time), KEY idx_slots_date(slot_date,department_id),
  CONSTRAINT fk_slots_department FOREIGN KEY(department_id) REFERENCES departments(id),
  CONSTRAINT fk_slots_service FOREIGN KEY(service_id) REFERENCES services(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, public_id CHAR(32) NOT NULL UNIQUE,
  reference_no VARCHAR(40) NOT NULL UNIQUE, slot_id BIGINT UNSIGNED NOT NULL,
  customer_name VARCHAR(255) NOT NULL, customer_phone VARCHAR(40) NOT NULL,
  source VARCHAR(20) NOT NULL DEFAULT 'ONLINE', status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
  idempotency_key VARCHAR(100) NULL UNIQUE, citizen_id_hash CHAR(64) NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_bookings_slot_status(slot_id,status),
  CONSTRAINT fk_bookings_slot FOREIGN KEY(slot_id) REFERENCES slots(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS queue_tickets (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, public_id CHAR(32) NOT NULL UNIQUE,
  booking_id BIGINT UNSIGNED NULL UNIQUE, queue_no VARCHAR(30) NOT NULL, source VARCHAR(20) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'WAITING', current_step VARCHAR(50) NOT NULL DEFAULT 'REGISTRATION_WAITING',
  checked_in_at DATETIME NOT NULL, first_called_at DATETIME NULL, registration_started_at DATETIME NULL,
  visit_opened_at DATETIME NULL, service_started_at DATETIME NULL, service_completed_at DATETIME NULL,
  estimated_wait_minutes INT UNSIGNED NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_queue_status(status,created_at),
  CONSTRAINT fk_queue_booking FOREIGN KEY(booking_id) REFERENCES bookings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS queue_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, queue_ticket_id BIGINT UNSIGNED NOT NULL,
  event_type VARCHAR(50) NOT NULL, status VARCHAR(30) NOT NULL, step VARCHAR(50) NOT NULL,
  note TEXT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_queue_events_ticket(queue_ticket_id,created_at),
  CONSTRAINT fk_events_queue FOREIGN KEY(queue_ticket_id) REFERENCES queue_tickets(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS hosxp_visit_links (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  queue_ticket_id BIGINT UNSIGNED NOT NULL UNIQUE,
  hn_hash CHAR(64) NOT NULL, hn_ciphertext TEXT NOT NULL, vn_ciphertext TEXT NULL,
  visit_date DATE NULL, visit_time TIME NULL, current_department VARCHAR(255) NULL,
  current_department_code VARCHAR(20) NULL, raw_status VARCHAR(50) NULL,
  sync_status VARCHAR(30) NOT NULL DEFAULT 'WAITING_FOR_VISIT', last_error VARCHAR(255) NULL,
  last_synced_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_hosxp_link_queue FOREIGN KEY(queue_ticket_id) REFERENCES queue_tickets(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
  action VARCHAR(80) NOT NULL, entity_type VARCHAR(80) NOT NULL, entity_id VARCHAR(100) NULL,
  detail LONGTEXT NULL, ip_address VARCHAR(64) NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_audit_created(created_at), CONSTRAINT fk_audit_user FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
